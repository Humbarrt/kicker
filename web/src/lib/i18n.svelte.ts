const dictionaries: Record<string, Partial<Record<Key, string>>> = { en, de };

export const languages = [
	{ code: 'en', name: 'English' },
	{ code: 'de', name: 'Deutsch' }
];

class I18n {
	lang = $state('en');
	/** Custom side names from the table settings (D17); '' = translated default. */
	sides = $state({ home: '', away: '' });

	set(code: string) {
		if (code in dictionaries) {
			this.lang = code;
			document.documentElement.lang = code;
		}
	}
}

export const i18n = new I18n();

/** Translates a key; {name} placeholders are replaced from params. */
export function t(key: Key, params?: Record<string, string | number>): string {
	let s: string = dictionaries[i18n.lang]?.[key] ?? en[key] ?? key;
	if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
	return s;
}

/** Translates an API error (ApiError.code), falling back to its message. */
export function tErr(e: unknown): string {
	const err = e as { code?: string; message?: string };
	const key = ('err.' + err?.code) as Key;
	if (err?.code && key in en) return t(key);
	return err?.message ?? String(e);
}

/** Translation of a permission key (labels for the groups editor). */
export function tPerm(key: string): string {
	return t(('perm.' + key) as Key);
}

/** Side name: the custom name from the table settings (D17), or Home / Away. */
export function tSide(side: string | null | undefined): string {
	if (side === 'home') return i18n.sides.home || t('side.home');
	if (side === 'away') return i18n.sides.away || t('side.away');
	return '';
}

/** Group name: the built-in groups are translated as long as they keep their original name. */
export function tGroup(g: { name: string; builtin?: string }): string {
	const original: Record<string, string> = { admin: 'Admin', member: 'Member', anybody: 'Anybody' };
	if (g.builtin && g.name === original[g.builtin]) return t(('group.' + g.builtin) as Key);
	return g.name;
}

/** Player name: the built-in guest is translated as long as it keeps its original name. */
export function tPlayer(p: { name: string; guest?: boolean }): string {
	return p.guest && p.name === 'Guest' ? t('player.guest') : p.name;
}
